package dev.ell.pillora.utils

import android.content.Context
import android.content.Intent
import dev.ell.pillora.data.Medicine
import dev.ell.pillora.water.WaterEntry
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ReportExporter {

    fun generateTextReport(
        medicines: List<Medicine>,
        waterEntries: List<WaterEntry>,
    ): String {
        val dateFormat = SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.getDefault())
        val dateOnly = SimpleDateFormat("dd MMM yyyy", Locale.getDefault())
        val generatedAt = dateFormat.format(Date())

        val builder = StringBuilder()
        builder.appendLine("==========================================")
        builder.appendLine("         PILLORA HEALTH & MED REPORT      ")
        builder.appendLine("==========================================")
        builder.appendLine("Generated: $generatedAt")
        builder.appendLine()

        builder.appendLine("--- ACTIVE MEDICINES & SCHEDULE ---")
        if (medicines.isEmpty()) {
            builder.appendLine("No active medicines logged.")
        } else {
            medicines.forEachIndexed { index, med ->
                builder.appendLine("${index + 1}. ${med.name} (${med.dosage})")
                builder.appendLine("   Type: ${med.type} | Time: ${med.reminderTime}")
                builder.appendLine("   Instruction: ${med.foodInstruction}")
                builder.appendLine("   Stock: ${med.stock} remaining")
                if (med.notes.isNotBlank()) {
                    builder.appendLine("   Notes: ${med.notes}")
                }
                builder.appendLine()
            }
        }

        builder.appendLine("--- HYDRATION LOG SUMMARY ---")
        if (waterEntries.isEmpty()) {
            builder.appendLine("No water intake recorded.")
        } else {
            val totalWater = waterEntries.sumOf { it.amountMl }
            builder.appendLine("Total Water Logged: $totalWater ml across ${waterEntries.size} entries")
            builder.appendLine("Recent Logs:")
            waterEntries.take(10).forEach { entry ->
                builder.appendLine(" - ${entry.amountMl} ml on ${dateOnly.format(Date(entry.timestamp))}")
            }
        }

        builder.appendLine()
        builder.appendLine("==========================================")
        builder.appendLine("Report generated by Pillora Health Companion")
        builder.appendLine("==========================================")

        return builder.toString()
    }

    fun shareReport(
        context: Context,
        medicines: List<Medicine>,
        waterEntries: List<WaterEntry>,
    ) {
        val reportText = generateTextReport(medicines, waterEntries)
        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, "Pillora Health & Medication Report")
            putExtra(Intent.EXTRA_TEXT, reportText)
        }
        context.startActivity(Intent.createChooser(shareIntent, "Export Health Report"))
    }
}
